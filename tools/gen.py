"""Regenerate board-derived components from the Claude Design board files in design/boards/.

Run: python3 tools/gen.py   (from the repo root)
Outputs src/boards/*.jsx + *.css. Hand edits belong in src/ (App, pages), not in src/boards.
"""
import re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from dc2jsx import Conv, scope_css
import json, html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = os.path.join(ROOT, 'design', 'boards')
OUT = os.path.join(ROOT, 'src', 'boards')
BLOB = re.compile(r'/_blob/([0-9a-f]{32})')

def parts(path):
    s = open(path).read()
    css = re.search(r'<style>(.*?)</style>', s, re.S).group(1)
    body = re.search(r'</helmet>(.*)</x-dc>', s, re.S).group(1).strip()
    m = re.search(r'data-props=(["\'])(.*?)\1>(.*?)</script>', s, re.S)
    props = json.loads(html.unescape(m.group(2)))
    rv = re.search(r'renderVals\(\)\s*\{(.*)\}\s*\}\s*$', m.group(3).strip(), re.S).group(1)
    return css, body, props, rv

def jsx(body):
    c = Conv(); c.feed(body); c.close(); return ''.join(c.out)

def blobs(t):
    return BLOB.sub(lambda m: '/a/' + m.group(1) + '.webp', t)

def write(name, scope, css, comps, rv, defaults):
    css = blobs(scope_css(css, '.' + scope))
    open(os.path.join(OUT, name + '.css'), 'w').write(css)
    src = ["/* Generated by tools/gen.py from design/boards — do not hand-edit; change the board or gen.py. */",
           "import React, { useState } from 'react'", "import './%s.css'" % name, '',
           'export const defaults = ' + json.dumps(defaults), '',
           'function renderVals() {' + blobs(rv) + '}', '',
           'function useVals(props) {',
           '  const [state, setRaw] = useState({})',
           '  const shim = { props: { ...defaults, ...props }, state, setState: (o) => setRaw((s) => ({ ...s, ...o })) }',
           '  return renderVals.call(shim)', '}', '']
    for cname, body in comps:
        src += ['export function %s(props) {' % cname, '  const v = useVals(props)',
                '  return (<div className="%s">%s</div>)' % (scope, blobs(jsx(body))), '}', '']
    open(os.path.join(OUT, name + '.jsx'), 'w').write('\n'.join(src))

def defaults_of(props):
    return {k: v.get('default') for k, v in props.items() if not k.startswith('$')}

# ---------- Restrained board -> LiveScoring + Franchise ----------
css, body, props, rv = parts(os.path.join(B, 'Restrained.dc.html'))
head = '<div class="root {{rootCls}}"><div class="wrap">'
a0 = body.index('<div class="sect first">Live scoring</div>') + len('<div class="sect first">Live scoring</div>')
a1 = body.index('<div class="sect">My Franchise</div>')
b0 = a1 + len('<div class="sect">My Franchise</div>')
b1 = body.rindex('</div>\n</div>')
live = head + body[a0:a1] + '</div></div>'
fr_head = '<div class="phd"><div><div class="eb">The Empire League · Week 7</div><h1 class="h1 d">My Franchise</h1></div></div>'
fr = head + fr_head + body[b0:b1] + '</div></div>'
# route-aware links inside pages
live = live.replace('<a class="btn" href="#">Game Day view</a>', '<a class="btn" href="#/gameday">Game Day view</a>')
d = defaults_of(props); d['dark'] = False
write('Restrained', 'b-r', css, [('LiveScoringBoard', live), ('FranchiseBoard', fr)], rv, d)

# ---------- Shell board -> AppShell (frame + Home content) ----------
css, body, props, rv = parts(os.path.join(B, 'Shell.dc.html'))
tabs = {'Home': 'home', 'My Franchise': 'franchise', 'Scores': 'scores', 'Standings': 'standings',
        'Players': 'players', 'Trades': 'trades', 'Clubhouse': 'clubhouse'}
body = body.replace('<a class="{{tabHome}}" href="#">Home</a>', '<a class="{{tabCls.home}}" href="#/home">Home</a>')
body = body.replace('<a class="tab" href="#">My Franchise', '<a class="{{tabCls.franchise}}" href="#/franchise">My Franchise')
body = body.replace('<a class="{{tabScores}}" href="#">Scores', '<a class="{{tabCls.scores}}" href="#/scores">Scores')
for t, r in [('Standings', 'standings'), ('Players', 'players'), ('Trades', 'trades'), ('Clubhouse', 'clubhouse')]:
    body = body.replace('<a class="tab" href="#">' + t, '<a class="{{tabCls.%s}}" href="#/%s">%s' % (r, r, t))
rail = [('Game Plan', 'gameplan'), ('The Wire', 'wire'), ('Chat', 'clubhouse'), ('Lineup', 'franchise'),
        ('Standings', 'standings'), ('Add', 'players'), ('More', 'more')]
for label, r in rail:
    body = re.sub(r'<a class="ri( on)?" href="#">(<svg.*?</svg><span>%s</span>)' % re.escape(label),
                  lambda m, r=r: '<a class="{{railCls.%s}}" href="#/%s">%s' % (r, r, m.group(2)), body, count=1)
body = body.replace('<a class="{{railScoresCls}}" href="#">', '<a class="{{railCls.scores}}" href="#/scores">')
body = body.replace('<a class="{{lgCls}}" href="#">', '<a class="{{lgCls}}" href="#" onclick="{{toggleFly}}">')
body = body.replace('<div class="lg">', '<div class="lg" onclick="{{toggleFly}}">')
body = body.replace('<div class="logo">', '<a class="logo" href="#/home">').replace('ball</i></div>', 'ball</i></a>')
# main: Home content from the board, other routes get children
m = re.search(r'<main class="page">(.*)</main>', body, re.S)
main = m.group(1)
home = re.search(r'<sc-if value="\{\{isHome\}\}"[^>]*>(.*?)</sc-if>', main, re.S).group(1)
hero = re.search(r"(<div class=\"\{\{heroCls\}\}\">.*?)(?=<div class=\"skrow\">)", main, re.S).group(1)
home = home.replace('<a class="hb pri" href="#">Set lineup</a>', '<a class="hb pri" href="{{heroHref}}">{{heroBtn}}</a>')
home = home.replace('<a class="hb" href="#">Live scoring</a>', '<a class="hb" href="#/scores">Live scoring</a>')
newmain = ('<main class="page"><sc-if value="{{isHome}}">' + home + '<a href="#/scores" class="herolink">' + hero +
           '</a></sc-if><sc-if value="{{notHome}}">{{children}}</sc-if></main>')
body = body[:m.start()] + newmain + body[m.end():]
rv = rv.replace('return {', '''var route = this.props.route || 'home';
    var tabCls = {}, railCls = {};
    ['home','franchise','scores','standings','players','trades','clubhouse'].forEach(function (k) { tabCls[k] = route === k ? 'tab on' : 'tab'; });
    ['gameplan','wire','clubhouse','franchise','scores','standings','players','more'].forEach(function (k) { railCls[k] = route === k ? 'ri on' : 'ri'; });
    return { tabCls: tabCls, railCls: railCls, notHome: route !== 'home', children: this.props.children, toggleFly: this.props.onToggleFly, heroBtn: this.props.heroBtn || 'Set lineup', heroHref: this.props.heroHref || '#/franchise',''', 1)
rv = rv.replace("home = pg === 'Home'", "home = (this.props.route || 'home') === 'home'")
css += '\n.logo{text-decoration:none}.herolink{display:block;color:inherit;text-decoration:none}.lg{user-select:none}'
d = defaults_of(props)
write('Shell', 'b-sh', css, [('ShellBoard', body)], rv, d)
print('ok')
